export function autoCheckReasonLabel(reason: string): string {
  if (!isBelarusian) return reason
  // Existing records store the message, with a count after the colon on numeric signals.
  const label = reason.replace(/ \d+$/, "")
  const translated = reasonLabelsBe.get(label)
  return translated ? translated + reason.slice(label.length) : reason
}

